"""Two-line Google Colab bootstrap for the AI-image narration studio.

Paste these two lines into a fresh Colab cell (T4 GPU runtime):

    !git clone -q https://github.com/Akashokshelke96/focusProtocol.git /content/focusProtocol
    !python /content/focusProtocol/deploy/colab_bootstrap.py --mode smoke

Then run ``--mode full`` for the real video, or ``--mode resume --job-id ...``.
The script changes into the repository root itself, so no ``%cd`` is needed.
It installs the narration extras, downloads the Piper voice, writes a Colab
``.env``, and runs the same ``NarrationStudio`` production path as the
dashboard, RunPod worker, and ``deploy/narration_ai_studio_colab.ipynb``.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path
from zipfile import ZIP_DEFLATED, ZipFile

REPO_ROOT = Path(__file__).resolve().parents[1]
VOICE_DIR = Path("/content/piper_voices")
VOICE_FILES = {
    "model": "en/en_US/lessac/medium/en_US-lessac-medium.onnx",
    "config": "en/en_US/lessac/medium/en_US-lessac-medium.onnx.json",
}
SMOKE_TOPIC = "What did ancient humans actually do all day?"


def run(command: list) -> None:
    print("$", " ".join(str(part) for part in command), flush=True)
    subprocess.run([str(part) for part in command], check=True, text=True)


def write_env(values: dict) -> Path:
    path = REPO_ROOT / ".env"
    if path.is_file():
        backup = REPO_ROOT / ".env.colab-backup"
        if not backup.exists():
            shutil.copy2(path, backup)
            print("Existing .env backed up to", backup)
    lines = [
        "# Generated by deploy/colab_bootstrap.py",
        "# Rerun with a different --topic/--mode; the model cache is reused.",
    ]
    lines.extend(f"{key}={value}" for key, value in values.items())
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def pip_install() -> None:
    run([sys.executable, "-m", "pip", "install", "-q",
         "-r", "deploy/requirements-narration-studio.txt"])


def check_gpu(min_vram_gb: float = 14.0) -> None:
    try:
        import torch
    except ImportError as error:
        raise SystemExit(
            "PyTorch is missing. In Colab choose Runtime > Change runtime type > "
            "T4 GPU, then rerun the same command.") from error
    if not torch.cuda.is_available():
        raise SystemExit(
            "No CUDA GPU detected. In Colab choose Runtime > Change runtime type > "
            "T4 GPU, then rerun the same command.")
    name = torch.cuda.get_device_name(0)
    vram = torch.cuda.get_device_properties(0).total_memory / (1024 ** 3)
    free_disk = shutil.disk_usage("/content").free / (1024 ** 3)
    print(f"GPU: {name} ({vram:.1f} GB VRAM) | free disk: {free_disk:.1f} GB")
    if vram < min_vram_gb:
        raise SystemExit(f"This SDXL + IP-Adapter profile needs at least {min_vram_gb:g} GB VRAM.")
    if free_disk < 18:
        raise SystemExit("Free at least 18 GB in the Colab runtime, then rerun.")


def prepare_voice() -> tuple[Path, Path]:
    from huggingface_hub import hf_hub_download

    VOICE_DIR.mkdir(parents=True, exist_ok=True)
    paths = {
        key: hf_hub_download(
            repo_id="rhasspy/piper-voices",
            filename=filename,
            local_dir=str(VOICE_DIR),
            token=os.getenv("HF_TOKEN") or None,
        )
        for key, filename in VOICE_FILES.items()
    }
    model = Path(paths["model"]).resolve()
    config = Path(paths["config"]).resolve()
    if not model.is_file() or model.stat().st_size < 1_000_000:
        raise SystemExit(f"Piper voice download failed: {model}")
    return model, config


