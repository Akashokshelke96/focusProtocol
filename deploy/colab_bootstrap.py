def package(job_id: str, report: dict) -> None:
    job_dir = REPO_ROOT / "jobs" / job_id
    video = Path(report.get("video") or job_dir / "output" / "rendered.mp4")
    thumbnail = Path(report.get("thumbnail") or job_dir / "thumbnail" / "thumbnail.png")
    if not video.is_file():
        print("No rendered MP4 was produced. Read the report above.")
        return
    output_root = Path("/content")
    if not output_root.is_dir():
        output_root = REPO_ROOT / "output"
    output_root.mkdir(parents=True, exist_ok=True)
    output = output_root / f"{job_id}_package.zip"
    wanted = [video, thumbnail, job_dir / "metadata.json",
              job_dir / "manifest" / "manifest.json",
              job_dir / "characters" / "character_bible.json"]
    with ZipFile(output, "w", ZIP_DEFLATED) as archive:
        for path in wanted:
            if path.is_file():
                archive.write(path, arcname=str(path.relative_to(job_dir)))
    print("Download package:", output)
    print("Video:", video)
    if thumbnail.is_file():
        print("Thumbnail:", thumbnail)


def main() -> int:
    parser = argparse.ArgumentParser(description="Colab one-command narration runner")
    parser.add_argument("--mode", choices=("smoke", "full", "resume"), default="smoke")
    parser.add_argument("--topic", default=SMOKE_TOPIC)
    parser.add_argument("--minutes", type=float, default=10.0)
    parser.add_argument("--smoke-seconds", type=int, default=30)
    parser.add_argument("--script", default="", help="Approved narration .txt for --mode full")
    parser.add_argument("--job-id", default="")
    parser.add_argument("--width", type=int, default=1280)
    parser.add_argument("--height", type=int, default=720)
    parser.add_argument("--fps", type=int, default=15)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--no-install", action="store_true")
    args = parser.parse_args()

    os.chdir(REPO_ROOT)
    print("Repository:", REPO_ROOT)
    check_gpu()
    if not args.no_install:
        pip_install()
    model, config = prepare_voice()
    configure(args.width, args.height, args.fps, args.seed, model, config,
              os.getenv("HF_TOKEN", ""))

    from app.narration.studio import NarrationStudio

    studio = NarrationStudio()
    if args.mode == "smoke":
        report = studio.smoke_test(args.topic, args.smoke_seconds,
                                   job_id=args.job_id or None)
    elif args.mode == "resume":
        if not args.job_id.strip():
            raise SystemExit("--job-id is required with --mode resume")
        ok = studio.resume(args.job_id.strip())
        report = studio.build_report(args.job_id.strip())
        report["ok"] = bool(ok and report.get("checks", {}).get("all_passed"))
    else:
        if args.script.strip():
            script_path = Path(args.script).expanduser()
            if not script_path.is_file():
                raise SystemExit(f"Script file not found: {script_path}")
            text = script_path.read_text(encoding="utf-8").strip()
            if len(text.split()) < 250:
                raise SystemExit("The approved script is too short for a full video.")
            from app.narration.models import ScriptPlan
            plan = ScriptPlan(
                topic=args.topic,
                title=args.topic[:90],
                script=text,
                word_count=len(text.split()),
                estimated_duration_seconds=round(len(text.split()) / 150.0 * 60, 2),
                approved=True,
            )
            ok = studio.run_script(plan, args.minutes, job_id=args.job_id or None)
        else:
            from app.config.settings import Settings
            from app.narration.llm import build_narration_llm
            if not build_narration_llm(Settings()).available:
                raise SystemExit(
                    "Full mode needs a text LLM key (OPENROUTER_API_KEY_NARRATOR, "
                    "GEMINI_API_KEY_NARRATOR, or OMNIROUTE_API_KEY_NARRATOR) or "
                    "--script <approved.txt>. Smoke mode needs no key.")
            ok = studio.run_topic(args.topic, args.minutes, auto_approve=True)
        report = studio.build_report(studio.last_job_id)
        report["ok"] = bool(ok and report.get("checks", {}).get("all_passed"))

    print(json.dumps(report, indent=2, default=str))
    job_id = report.get("job_id") or ""
    if job_id:
        package(job_id, report)
    return 0 if report.get("ok") else 1


if __name__ == "__main__":
    raise SystemExit(main())
