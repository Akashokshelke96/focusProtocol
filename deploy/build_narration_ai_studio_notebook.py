def main() -> int:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(json.dumps(NOTEBOOK, ensure_ascii=False, indent=1), encoding="utf-8")
    loaded = json.loads(OUTPUT.read_text(encoding="utf-8"))
    code_cells = [cell for cell in loaded["cells"] if cell["cell_type"] == "code"]
    if len(code_cells) != 2:
        raise ValueError(f"Expected exactly two code cells, found {len(code_cells)}")
    for index, cell in enumerate(code_cells, start=1):
        source = "".join(cell["source"])
        compile(source, f"{OUTPUT.name}:code-{index}", "exec")
        if "/content/focusProtocol" not in source and index == 1:
            raise ValueError("Setup cell must default to the Colab repository path")
    combined = "\n".join("".join(cell["source"]) for cell in code_cells).lower()
    if "stickman" in combined:
        raise ValueError("The studio notebook must not reference the stickman renderer")
    print(f"Wrote {OUTPUT.resolve()} with {len(code_cells)} code cells")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
