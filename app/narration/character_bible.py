"""Persistent character bible: cast, identity anchors, and style lock.

The bible is the source of truth for every reference image and every scene
prompt. It is generated once per script, fingerprinted, and reused on resume.
A deterministic fallback keeps the pipeline usable when no text LLM is
reachable; it is clearly marked as ``source="fallback"``.
"""
from __future__ import annotations

import hashlib
import json
import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional

from app.config.logging_config import get_logger
from app.config.settings import Settings
from app.narration.models import (
    CharacterBible,
    CharacterReference,
    CharacterSpec,
    ScriptPlan,
)
from app.narration.prompts import NARRATION_CHARACTER_BIBLE_PROMPT
from app.narration.seeding import stable_seed

logger = get_logger("narration.characters")

BIBLE_VERSION = 1
BIBLE_FILENAME = "character_bible.json"

_ANCIENT_HINTS = (
    "ancient", "prehistoric", "prehistory", "stone age", "paleolithic",
    "mesolithic", "neolithic", "hunter-gather", "hunter gatherer",
    "neanderthal", "forager", "foraging",
)


def _slug(value: str, fallback: str = "character") -> str:
    cleaned = re.sub(r"[^a-z0-9]+", "_", (value or "").lower()).strip("_")
    return cleaned[:40] or fallback


def script_fingerprint(plan: ScriptPlan, style: str = "", direction: str = "") -> str:
    """Stable identity for the script + visual direction that owns a bible."""
    digest = hashlib.sha256()
    for part in (plan.topic, plan.title, plan.script, style, direction):
        digest.update((part or "").encode("utf-8"))
        digest.update(b"\0")
    return digest.hexdigest()[:20]


def _clean_text(value: Any, limit: int = 1200) -> str:
    text = re.sub(r"\s+", " ", str(value or "")).strip()
    return text[:limit]


def _as_list(value: Any, limit: int = 8) -> list[str]:
    if isinstance(value, str):
        items = [item.strip() for item in value.split(",")]
    elif isinstance(value, (list, tuple)):
        items = [str(item).strip() for item in value]
    else:
        items = []
    return [item for item in items if item][:limit]


class CharacterBibleBuilder:
    """Builds, validates, and persists the recurring cast for one video."""

    def __init__(self, settings: Settings, llm: Any = None):
        self.settings = settings
        self.llm = llm

    # ------------------------------------------------------------------ public
    def load_or_build(
        self,
        plan: ScriptPlan,
        job_dir: Path,
        style_prefix: Optional[str] = None,
        creative_direction: Optional[str] = None,
        force: bool = False,
    ) -> CharacterBible:
        style = (style_prefix or self.settings.narration_style_prefix or "").strip()
        direction = (creative_direction if creative_direction is not None
                     else self.settings.narration_creative_direction or "").strip()
        expected = script_fingerprint(plan, style, direction)
        path = Path(job_dir) / "characters" / BIBLE_FILENAME
        if not force and path.is_file():
            existing = self.load(Path(job_dir))
            if existing and existing.fingerprint == expected:
                logger.info("Reusing character bible (%s characters, %s)",
                            len(existing.characters), existing.fingerprint)
                return existing

        bible = self.build(plan, style, direction)
        bible.fingerprint = expected
        self.save(bible, Path(job_dir))
        return bible

    def build(self, plan: ScriptPlan, style_prefix: str = "",
              creative_direction: str = "") -> CharacterBible:
        style = (style_prefix or self.settings.narration_style_prefix or "").strip()
        prompt = NARRATION_CHARACTER_BIBLE_PROMPT.format(
            title=plan.title or plan.topic,
            topic=plan.topic,
            style_prefix=style,
            creative_direction=creative_direction or "(none supplied)",
            script_excerpt=(plan.script or "")[:6000],
        )
        if self.llm is not None:
            try:
                payload = self.llm.generate_json(prompt)
                bible = self._from_payload(payload, style, plan)
                if bible:
                    bible.fingerprint = script_fingerprint(plan, style, creative_direction)
                    logger.info("Character bible generated by LLM: %s characters",
                                len(bible.characters))
                    return bible
            except Exception as error:  # noqa: BLE001 - deterministic fallback
                logger.warning("Character bible LLM failed (%s); using fallback cast", error)
        bible = self._fallback(plan, style)
        bible.fingerprint = script_fingerprint(plan, style, creative_direction)
        logger.warning("Using deterministic fallback character bible for %r", plan.topic)
        return bible

    def save(self, bible: CharacterBible, job_dir: Path) -> Path:
        path = Path(job_dir) / "characters" / BIBLE_FILENAME
        path.parent.mkdir(parents=True, exist_ok=True)
        temp = path.with_suffix(".json.tmp")
        temp.write_text(json.dumps(bible.model_dump(), indent=2, ensure_ascii=False),
                        encoding="utf-8")
        temp.replace(path)
        return path

    @staticmethod
    def load(job_dir: Path) -> Optional[CharacterBible]:
        path = Path(job_dir) / "characters" / BIBLE_FILENAME
        if not path.is_file():
            return None
        try:
            return CharacterBible.model_validate_json(path.read_text(encoding="utf-8"))
        except Exception as error:  # noqa: BLE001 - corrupt cache is rebuilt
            logger.warning("Ignoring unreadable character bible %s: %s", path, error)
            return None

    # --------------------------------------------------------------- validation
    def _from_payload(self, payload: Any, style: str, plan: ScriptPlan) -> Optional[CharacterBible]:
        if not isinstance(payload, dict):
            return None
        records = payload.get("characters")
        if not isinstance(records, list) or not records:
            return None

        characters: list[CharacterSpec] = []
        seen: set[str] = set()
        for position, record in enumerate(records[:3]):
            if not isinstance(record, dict):
                continue
            name = _clean_text(record.get("name") or record.get("id"), 80)
            identity = _clean_text(record.get("identity"), 1200)
            if not name or len(identity.split()) < 8:
                continue
            character_id = _slug(record.get("id") or name, f"character_{position + 1}")
            while character_id in seen:
                character_id = f"{character_id}_{position + 1}"
            seen.add(character_id)
            wardrobe = _clean_text(record.get("wardrobe"), 600)
            features = _clean_text(record.get("distinguishing_features"), 400)
            palette = _clean_text(record.get("palette"), 200)
            seed = stable_seed(self.settings.narration_seed, "character", character_id, identity)
            reference_prompt = _clean_text(record.get("reference_prompt"), 1200) or (
                f"Full-body character reference of {name}. {identity} Wearing {wardrobe} "
                "Standing in a relaxed neutral pose, whole body visible, arms slightly away "
                "from the torso, neutral warm grey seamless backdrop, soft even studio light, "
                "sharp focus on the face and clothing."
            )
            portrait_prompt = _clean_text(record.get("portrait_prompt"), 1200) or (
                f"Head-and-shoulders character reference of {name}. {identity} Wearing the "
                f"collar and upper part of {wardrobe or 'the fixed outfit'}, neutral warm grey "
                "backdrop, soft even studio light, looking toward the camera, sharp focus."
            )
            characters.append(CharacterSpec(
                id=character_id,
                name=name,
                role=_clean_text(record.get("role") or ("primary" if position == 0 else "supporting"), 40),
                identity=identity,
                wardrobe=wardrobe,
                distinguishing_features=features,
                palette=palette,
                reference_prompt=reference_prompt,
                portrait_prompt=portrait_prompt,
                forbidden_changes=_as_list(record.get("forbidden_changes")) or [
                    "do not change face shape, apparent age, or skin tone",
                    "do not change hair colour, hairline, or hairstyle",
                    "do not change the fixed outfit or its colours",
                    "do not add text, logos, or modern objects not in the scene",
                ],
                seed=seed,
            ))

        if not characters:
            return None
        style_lock = _clean_text(payload.get("style_lock"), 900) or style
        return CharacterBible(
            version=BIBLE_VERSION,
            style_lock=style_lock,
            characters=characters,
            source="llm",
            created_at=datetime.now(timezone.utc).isoformat(),
            notes=_clean_text(payload.get("notes"), 600),
        )

    def _fallback(self, plan: ScriptPlan, style: str) -> CharacterBible:
        text = f"{plan.topic} {plan.title} {plan.script[:4000]}".lower()
        ancient = any(hint in text for hint in _ANCIENT_HINTS)
        if ancient:
            records = _ancient_cast()
        else:
            records = _documentary_cast()

        characters: list[CharacterSpec] = []
        for record in records:
            character_id = _slug(record["name"])
            characters.append(CharacterSpec(
                id=character_id,
                seed=stable_seed(self.settings.narration_seed, "character", character_id,
                                 record["identity"]),
                **record,
            ))
        return CharacterBible(
            version=BIBLE_VERSION,
            style_lock=style,
            characters=characters,
            source="fallback",
            created_at=datetime.now(timezone.utc).isoformat(),
            notes=("Deterministic fallback cast. The narration LLM was unavailable; "
                   "identities are intentionally generic and should be reviewed."),
        )


